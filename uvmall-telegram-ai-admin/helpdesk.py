def topic_by_words(text):
    s = text.lower().strip()
    if "модерац" in s or "отклон" in s: return ("seller", "moderation")
    if "excel" in s or "эксел" in s or "таблиц" in s: return ("seller", "excel")
    if "не загруж" in s and ("фото" in s or "изображен" in s): return ("tech", "photos")
    if "ошибк" in s and ("сайт" in s or "страниц" in s): return ("tech", "error")
    if "не могу войти" in s or "не входит" in s or "не удаётся войти" in s: return ("tech", "login")
    if "оптовая цена" in s or "опт цена" in s or "минимальная партия" in s: return ("buyer", "wholesale")
    if "статус заказа" in s or "где мой заказ" in s: return ("buyer", "orders")
    if "доставк" in s or "самовывоз" in s: return ("buyer", "shipping")
    if "возврат" in s or "вернуть товар" in s: return ("buyer", "return")
    if "безопасност" in s or "мошенник" in s: return ("tech", "security")
    return None

def topic_by_number(section, number):
    """Map 1-based textual help-menu choices to stable FAQ keys."""
    meta = SECTIONS.get(section)
    if not meta: return None
    try:
        i = int(str(number).strip()) - 1
    except (ValueError, TypeError):
        return None
    keys = list(meta["topics"])
    return keys[i] if 0 <= i < len(keys) else None
